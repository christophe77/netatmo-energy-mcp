#!/usr/bin/env node
/**
 * Generates docs/tools.md from the tools, resources and prompts the built server actually
 * exposes, so the reference cannot drift from the code.
 *
 * Usage: pnpm build && node scripts/gen-tools-doc.mjs [--check]
 *   --check  exit 1 if docs/tools.md is out of date (used in CI)
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';

const root = path.resolve(import.meta.dirname, '..');
const target = path.join(root, 'docs', 'tools.md');
const work = mkdtempSync(path.join(tmpdir(), 'nem-doc-'));

const transport = new StdioClientTransport({
  command: process.execPath,
  args: [path.join(root, 'dist', 'index.js')],
  env: {
    ...process.env,
    NETATMO_MCP_CONFIG_DIR: path.join(work, 'cfg'),
    NETATMO_MCP_LOG_LEVEL: 'silent',
  },
});
const client = new Client({ name: 'gen-tools-doc', version: '0.0.0' });
await client.connect(transport);
const { tools } = await client.listTools();
const { resourceTemplates } = await client.listResourceTemplates();
const { prompts } = await client.listPrompts();
await client.close();
rmSync(work, { recursive: true, force: true });

const esc = (s) =>
  String(s ?? '')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ');

function typeOf(schema) {
  if (!schema) return 'any';
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(' \\| ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' \\| ');
  if (Array.isArray(schema.type)) return schema.type.join(' \\| ');
  if (schema.type === 'array') return `${typeOf(schema.items)}[]`;
  const bounds = [];
  if (schema.minimum !== undefined) bounds.push(`≥ ${schema.minimum}`);
  if (schema.maximum !== undefined) bounds.push(`≤ ${schema.maximum}`);
  if (schema.maxLength !== undefined) bounds.push(`≤ ${schema.maxLength} chars`);
  return `${schema.type ?? 'object'}${bounds.length ? ` (${bounds.join(', ')})` : ''}`;
}

const groups = [
  [
    'Discovery',
    ['netatmo_list_homes', 'netatmo_get_home', 'netatmo_list_rooms', 'netatmo_list_devices'],
  ],
  [
    'Current status',
    [
      'netatmo_get_home_status',
      'netatmo_get_room_status',
      'netatmo_get_heating_status',
      'netatmo_get_device_status',
    ],
  ],
  [
    'History',
    [
      'netatmo_get_temperature_history',
      'netatmo_get_setpoint_history',
      'netatmo_get_boiler_history',
    ],
  ],
  [
    'Analytics',
    ['netatmo_get_heating_summary', 'netatmo_compare_rooms', 'netatmo_detect_anomalies'],
  ],
];

const out = [
  '# MCP reference',
  '',
  '<!-- Generated by scripts/gen-tools-doc.mjs from the running server. Do not edit by hand. -->',
  '',
  `${tools.length} tools, all **read-only** (\`readOnlyHint: true\`). Every tool returns`,
  '`structuredContent` (JSON matching its output schema) plus the same JSON as text. Errors are',
  'returned as results with `isError: true` and a body `{ "error": { "code", "message", "hint" } }`.',
  '',
  'Error codes: `AUTH_REQUIRED`, `PERMISSION_DENIED`, `RATE_LIMITED`, `NOT_FOUND`,',
  '`INVALID_ARGUMENT`, `UNSUPPORTED_CAPABILITY`, `NETATMO_UNAVAILABLE`, `INVALID_RESPONSE`.',
  '',
  'Conventions: temperatures in °C, durations in minutes, times in ISO 8601 with the home UTC',
  'offset, `null` = not reported by Netatmo. Periods: `today`, `yesterday`, `last_24h`,',
  '`last_7d`, `last_30d` (home time zone), or `from`/`to` ISO 8601.',
  '',
];

const known = new Set(groups.flatMap(([, names]) => names));
const extra = tools.map((t) => t.name).filter((n) => !known.has(n));
if (extra.length) groups.push(['Other', extra]);

for (const [title, names] of groups) {
  out.push(`## ${title}`, '');
  for (const name of names) {
    const tool = tools.find((t) => t.name === name);
    if (!tool) throw new Error(`Tool ${name} is not registered`);
    out.push(`### \`${tool.name}\``, '', tool.description ?? '', '');
    const props = tool.inputSchema?.properties ?? {};
    const required = new Set(tool.inputSchema?.required ?? []);
    const entries = Object.entries(props);
    if (entries.length === 0) {
      out.push('No arguments.', '');
    } else {
      out.push('| Argument | Type | Description |', '|---|---|---|');
      for (const [arg, schema] of entries) {
        out.push(
          `| \`${arg}\`${required.has(arg) ? ' (required)' : ''} | ${typeOf(schema)} | ${esc(schema.description)} |`,
        );
      }
      out.push('');
    }
    const outputs = Object.keys(tool.outputSchema?.properties ?? {});
    if (outputs.length) out.push(`Returns: ${outputs.map((k) => `\`${k}\``).join(', ')}.`, '');
  }
}

out.push(
  '## Resources',
  '',
  'All resources are `application/json`.',
  '',
  '| URI | Description |',
  '|---|---|',
);
out.push('| `netatmo://homes` | Homes with Netatmo Energy devices |');
for (const r of resourceTemplates) out.push(`| \`${r.uriTemplate}\` | ${esc(r.description)} |`);
out.push('', '## Prompts', '', '| Prompt | Arguments | Description |', '|---|---|---|');
for (const p of prompts) {
  const args = (p.arguments ?? []).map((a) => `\`${a.name}\``).join(', ') || '—';
  out.push(`| \`${p.name}\` | ${args} | ${esc(p.description)} |`);
}
out.push('');

const content = out.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing
  }
  if (current.replace(/\r\n/g, '\n') !== content) {
    console.error('docs/tools.md is out of date. Run: pnpm build && pnpm docs:tools');
    process.exit(1);
  }
  console.log('docs/tools.md is up to date.');
} else {
  writeFileSync(target, content);
  console.log(`Wrote ${path.relative(root, target)} (${tools.length} tools).`);
}
